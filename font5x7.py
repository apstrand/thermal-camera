"""A 5x7 bitmap font and a text renderer for raw RGB565 strips.

displayio is not used in the fast path, so the readout is drawn by hand.
Only the glyphs the readout needs are included. Each glyph is 5 bytes, one
per column, bits 0..6 running top to bottom.
"""

CHARS = "0123456789.-: ACFHIMNPRSTX"

GLYPHS = bytes(
    (
        0x3E, 0x51, 0x49, 0x45, 0x3E,   # 0
        0x00, 0x42, 0x7F, 0x40, 0x00,   # 1
        0x42, 0x61, 0x51, 0x49, 0x46,   # 2
        0x21, 0x41, 0x45, 0x4B, 0x31,   # 3
        0x18, 0x14, 0x12, 0x7F, 0x10,   # 4
        0x27, 0x45, 0x45, 0x45, 0x39,   # 5
        0x3C, 0x4A, 0x49, 0x49, 0x30,   # 6
        0x01, 0x71, 0x09, 0x05, 0x03,   # 7
        0x36, 0x49, 0x49, 0x49, 0x36,   # 8
        0x06, 0x49, 0x49, 0x29, 0x1E,   # 9
        0x00, 0x60, 0x60, 0x00, 0x00,   # .
        0x08, 0x08, 0x08, 0x08, 0x08,   # -
        0x00, 0x14, 0x00, 0x00, 0x00,   # :
        0x00, 0x00, 0x00, 0x00, 0x00,   # space
        0x7E, 0x11, 0x11, 0x11, 0x7E,   # A
        0x3E, 0x41, 0x41, 0x41, 0x22,   # C
        0x7F, 0x09, 0x09, 0x09, 0x01,   # F
        0x7F, 0x08, 0x08, 0x08, 0x7F,   # H
        0x00, 0x41, 0x7F, 0x41, 0x00,   # I
        0x7F, 0x02, 0x0C, 0x02, 0x7F,   # M
        0x7F, 0x04, 0x08, 0x10, 0x7F,   # N
        0x7F, 0x09, 0x09, 0x09, 0x06,   # P
        0x7F, 0x09, 0x19, 0x29, 0x46,   # R
        0x46, 0x49, 0x49, 0x49, 0x31,   # S
        0x01, 0x01, 0x7F, 0x01, 0x01,   # T
        0x63, 0x14, 0x08, 0x14, 0x63,   # X
    )
)

ADVANCE = 6      # glyph width + 1 column of spacing
HEIGHT = 7


def draw(strip, width, text, x, y, fg_hi, fg_lo):
    """Draw `text` into `strip`, a bytearray of big-endian RGB565 pixels.

    Only foreground pixels are written, so the caller pre-fills the
    background. fg_hi/fg_lo are the two colour bytes, already in panel order.
    """
    for ch in text:
        g = CHARS.find(ch)
        if g < 0:
            x += ADVANCE
            continue
        base = g * 5
        for col in range(5):
            bits = GLYPHS[base + col]
            if not bits:
                continue
            px = x + col
            if px < 0 or px >= width:
                continue
            for row in range(HEIGHT):
                if bits & (1 << row):
                    o = ((y + row) * width + px) * 2
                    strip[o] = fg_hi
                    strip[o + 1] = fg_lo
        x += ADVANCE
    return x
